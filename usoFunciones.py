import math

numUno = float(input("Ingrese numero uno: "))

print("El seno es:", math.sin(numUno))
print("El coseno es:", math.cos(numUno))
print("La tangente es:", math.tan(numUno))
print("La raiz es:", math.sqrt(numUno))
print("El logaritmo natural es:", math.log(numUno))
print("El logaritmo (base 10) es:", math.log(numUno) / math.log(10))
